namespace TicTacToeApplication.Models.Enums;

/// <summary>
/// Contains the main menu options.
/// </summary>
internal enum MainMenuOption
{
    /// <summary>
    /// Represents the option to start a new game.
    /// </summary>
    NewGame = 1,

    /// <summary>
    /// Represents a option to view previous match history.
    /// </summary>
    History,

    /// <summary>
    /// Represents a option to view the user profile.
    /// </summary>
    Profile,

    /// <summary>
    /// Represents a option to check the leaderboard.
    /// </summary>
    LeaderBoard,

    /// <summary>
    /// Represents a option to logout from the application.
    /// </summary>
    Logout,
}
