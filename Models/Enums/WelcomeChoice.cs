namespace TicTacToeApplication.Models.Enums;

/// <summary>
/// Contains the option to login to application.
/// </summary>
internal enum WelcomeChoice
{
    /// <summary>
    /// Represents a option to login to the application.
    /// </summary>
    Login = 1,

    /// <summary>
    /// Represents a option to signup to the application.
    /// </summary>
    SignUp,

    /// <summary>
    /// Represents a option to login as guest to the application.
    /// </summary>
    Guest,

    /// <summary>
    /// Represents a option to exit the application.
    /// </summary>
    Exit,
}
