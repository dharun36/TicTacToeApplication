namespace TicTacToeApplication.Models.Enums;

/// <summary>
/// Contains the game mode options available.
/// </summary>
internal enum GameMode
{
    /// <summary>
    /// Represents the option to start a easy difficulty game.
    /// </summary>
    Easy = 1,

    /// <summary>
    /// Represents the option to start a medium difficulty game.
    /// </summary>
    Medium,

    /// <summary>
    /// Represents the option to start a hard difficulty game.
    /// </summary>
    Hard,

    /// <summary>
    /// Represents the option to start a manual game.
    /// </summary>
    Manual,
}
