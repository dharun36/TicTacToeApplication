namespace TicTacToeApplication.Models.Enums;

/// <summary>
/// Contains the symbols in the board.
/// </summary>
internal enum Symbol
{
    /// <summary>
    /// Represents a empty cell.
    /// </summary>
    Empty = 0,

    /// <summary>
    /// Represents a cell with symbol 'X'.
    /// </summary>
    X = 1,

    /// <summary>
    /// Represents a cell with symbol 'O'.
    /// </summary>
    O,
}
